package com.example;

public class Ejercicio5 {
    public static void ejercicio5() {

// Declarar y aplicar descuento
        double precio = 100.0;
        precio *= 0.85; // Aplica 15% de descuento

// Concatenar mensaje
        String mensaje = "Hola";
        mensaje += " Mundo"; // Concatena texto

// Manipular puntos
        int puntos = 50;
        puntos *= 2;   // Duplica los puntos
        puntos += 25;  // Se  adiciona 25

// Imprimir resultados
        System.out.println("Precio con descuento: $" + precio);
        System.out.println("Mensaje completo: " + mensaje);
        System.out.println("Puntos totales: " + puntos);
    }

    public static void main(String[] args) {
        ejercicio5();


    }
}
